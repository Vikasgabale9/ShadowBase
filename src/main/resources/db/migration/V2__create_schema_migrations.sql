
CREATE TABLE schema_migrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    migration_name VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    source_database VARCHAR(100) NOT NULL,
    shadow_database VARCHAR(100),
    source_schema_version VARCHAR(50),
    target_schema_version VARCHAR(50),
    migration_status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    created_by VARCHAR(150) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_schema_migrations_created_by
    ON schema_migrations(created_by);

CREATE INDEX idx_schema_migrations_status
    ON schema_migrations(migration_status);
